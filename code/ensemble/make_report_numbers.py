def size_boost(m: Macros) -> None:
    a = json.loads((RESULTS / "analysis_sweeps.json").read_text())
    for c, tag in (("plain", "Plain"), ("weighted", "Weighted"), ("sampled", "Sampled")):
        t = read(f"summary_size_{c}.csv")
        if t is None:
            continue
        t = t.set_index("n_estimators")
        for b in (1, 10, 50, 100, 200, 500, 2000):
            if b in t.index:
                m.add(f"OSize{tag}{WORDS.get(b, str(b))}F", f3(t.loc[b, "macro_f1_mean"]))
                m.add(f"OSize{tag}{WORDS.get(b, str(b))}FStd", f3(t.loc[b, "macro_f1_std"]))
        m.add(f"OSize{tag}DimAt", a[f"diminishing_size_{c}"]["diminishing_at"])
        m.add(f"OSize{tag}OobDimAt", a[f"diminishing_size_{c}_oob"]["diminishing_at"])
        last = t.index.max()
        m.add(f"OSize{tag}Oob", f3(t.loc[last, "oob_macro_f1_mean"]))
        m.add(f"OSize{tag}Dis", f3(t.loc[last, "disagreement_mean"]))
        m.add(f"OSize{tag}Strength", f3(t.loc[last, "member_accuracy_mean"]))
        m.add(f"OSize{tag}Acc", f3(t.loc[last, "accuracy_mean"]))
        m.add(f"OSize{tag}OneAcc", f3(t.loc[1, "accuracy_mean"]))
        m.add(f"OSize{tag}GainLast", f"{t.loc[last, 'macro_f1_mean'] - t.loc[500, 'macro_f1_mean']:+.4f}")
        m.add(f"OSize{tag}CoverageTwo", f3(t.loc[2, "oob_coverage_mean"]))
    b = read("summary_boosting_size.csv")
    if b is not None:
        b = b.set_index("n_estimators")
        peak = b["macro_f1_mean"].idxmax()
        last = b.index.max()
        m.add("OBoostPeakAt", int(peak))
        m.add("OBoostLast", int(last))
        for nm, idx in (("Peak", peak), ("Last", last), ("One", 1)):
            m.add(f"OBoost{nm}F", f3(b.loc[idx, "macro_f1_mean"]))
            m.add(f"OBoost{nm}FStd", f3(b.loc[idx, "macro_f1_std"]))
            m.add(f"OBoost{nm}Train", f3(b.loc[idx, "train_error_mean"]))
            m.add(f"OBoost{nm}Dis", f3(b.loc[idx, "disagreement_mean"]))
            m.add(f"OBoost{nm}Acc", f3(b.loc[idx, "accuracy_mean"]))


def search(m: Macros) -> None:
    tf = json.loads((RESULTS / "tuned_forests.json").read_text())
    s2 = read("joint_stage2_summary.csv").set_index("config")
    m.add("OJStageOne", tf["stage1_configs"])
    m.add("OJStageTwo", tf["stage2_configs"])
    for fam, tag in FAM.items():
        p = tf[fam]["params"]
        m.add(f"OJ{tag}F", f3(tf[fam]["macro_f1_mean"]))
        m.add(f"OJ{tag}FStd", f3(tf[fam]["macro_f1_std"]))
        m.add(f"OJ{tag}Config", tf[fam]["config"])
        m.add(f"OJ{tag}Features", p["max_features"])
        m.add(f"OJ{tag}Depth", "none" if p["max_depth"] in (None, "None") else p["max_depth"])
        m.add(f"OJ{tag}Leaf", p["min_samples_leaf"])
        m.add(f"OJ{tag}Criterion", p["criterion"])
        m.add(f"OJ{tag}Alpha", p["class_weight_power"])
        m.add(f"OJ{tag}Omega", p["sampling_power"])
        m.add(f"OJ{tag}Sampler", "undersampling" if p["sampling"] == "under" else "bootstrap")
        m.add(f"OJ{tag}Size", p["class_sample_size"] if p["class_sample_size"] not in (None, "None") else "none")
        r = s2.loc[tf[fam]["config"]]
        m.add(f"OJ{tag}Acc", f3(r["accuracy_mean"]))
        m.add(f"OJ{tag}Bal", f3(r["balanced_accuracy_mean"]))
    for i in range(7):
        c = f"f{i}"
        if c in s2.index:
            m.add(f"OForced{WORDS.get(i, CLS[i])}F", f3(s2.loc[c, "macro_f1_mean"]))
    m.add("OJBest", f3(s2["macro_f1_mean"].max()))
    m.add("OJPlainGap", f3(tf["weighted"]["macro_f1_mean"] - tf["plain"]["macro_f1_mean"]))
    s1 = read("joint_stage1.csv")
    g1 = s1.groupby("config")["macro_f1"].mean()
    m.add("OJStageOneBest", f3(g1.max()))
    m.add("OJStageOneWorst", f3(g1.min()))
    # search table
    lines = ["% Generated by code/ensemble/make_report_numbers.py. Do not edit by hand.",
             "\\begin{table}[t]", "\\caption{Best configuration of each family in the joint search}",
             "\\label{tab:search}", "\\centering", "\\footnotesize", "\\setlength{\\tabcolsep}{2.5pt}",
             "\\begin{tabular}{lccccccc}", "\\toprule",
             "Family & $\\varphi$ & Depth & Leaf & $\\alpha$ & Sampler & Macro-F1 & Bal. acc. \\\\", "\\midrule"]
    for fam in FAM:
        p = tf[fam]["params"]
        r = s2.loc[tf[fam]["config"]]
        smp = (f"$\\omega = {p['sampling_power']}$" if p["sampling"] == "bootstrap" and p["sampling_power"] > 0
               else (f"under {p['class_sample_size']}" if p["sampling"] == "under" else "standard"))
        d = "none" if p["max_depth"] in (None, "None") else p["max_depth"]
        lines.append(f"{fam} & {p['max_features']} & {d} & {p['min_samples_leaf']} & {p['class_weight_power']} & {smp} & "
                     f"{f3(r['macro_f1_mean'])} $\\pm$ {f3(r['macro_f1_std'])} & {f3(r['balanced_accuracy_mean'])} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    (OUT / "table_search.tex").write_text("\n".join(lines) + "\n")
    tb = json.loads((RESULTS / "tuned_boosting.json").read_text())
    g = read("boosting_grid_summary.csv")
    m.add("OBoostTunedDepth", tb["params"]["max_depth"])
    m.add("OBoostTunedRate", tb["params"]["learning_rate"])
    m.add("OBoostTunedAlpha", tb["params"]["class_weight_power"])
    m.add("OBoostTunedRounds", tb["n_estimators"])
    m.add("OBoostTunedF", f3(tb["macro_f1_mean"]))
    m.add("OBoostTunedFStd", f3(tb["macro_f1_std"]))
    m.add("OBoostGridN", tb["n_configurations"])
    for d in sorted(g["max_depth"].unique()):
        m.add(f"OBoostGridDepth{WORDS.get(int(d), str(int(d)))}Best", f3(g[g.max_depth == d]["macro_f1_mean"].max()))
    m.add("OBoostGridBestWeighted", f3(g[g.class_weight_power > 0]["macro_f1_mean"].max()))
    r1 = g[g.learning_rate == 1.0]["macro_f1_mean"].max()
    m.add("OBoostGridBestRateOne", f3(r1))


