def protocols(m: Macros) -> None:
    for p, ptag in PROTO.items():
        s = read(f"protocol_summary_{p}.csv")
        if s is None:
            continue
        s = s.set_index("model")
        for mod in s.index:
            if mod not in TAG:
                continue
            r = s.loc[mod]
            for k, nm in MEASURES.items():
                m.add(f"OP{ptag}{TAG[mod]}{nm}", f3(r[f"{k}_mean"]))
                m.add(f"OP{ptag}{TAG[mod]}{nm}Std", f3(r[f"{k}_std"]))
                m.add(f"OP{ptag}{TAG[mod]}{nm}RunStd", f"{r[f'{k}_run_std']:.4f}")
            for c, nm in (("accuracy_none", "AccNone"), ("accuracy_consistent", "AccCons"),
                          ("accuracy_conflicting", "AccConf"), ("oob_macro_f1", "OobF"), ("disagreement", "Dis"),
                          ("member_accuracy", "Strength")):
                if f"{c}_mean" in r and not pd.isna(r[f"{c}_mean"]):
                    m.add(f"OP{ptag}{TAG[mod]}{nm}", f3(r[f"{c}_mean"]))
        if "n_none_mean" in s.columns and "tree" in s.index:
            tot = s.loc["tree", ["n_none_mean", "n_consistent_mean", "n_conflicting_mean"]].sum()
            for c, nm in (("n_none_mean", "None"), ("n_consistent_mean", "Cons"), ("n_conflicting_mean", "Conf")):
                m.add(f"OP{ptag}Share{nm}", f"{100 * s.loc['tree', c] / tot:.1f}")
            m.add(f"OP{ptag}TwinShare", f"{100 * (1 - s.loc['tree', 'n_none_mean'] / tot):.1f}")
        m.add(f"OP{ptag}Runs", word(s.loc["rf", "n_runs"]))
        st = read(f"protocol_stats_{p}.csv")
        for _, r in st.iterrows():
            tag = f"OS{ptag}{TAG[r['model_a']]}Vs{TAG[r['model_b']]}{MEASURES[r['measure']]}"
            m.add(f"{tag}Diff", f"{r['mean_diff']:+.3f}")
            m.add(f"{tag}AbsDiff", f3(abs(r["mean_diff"])))
            m.add(f"{tag}Dz", f"{r['cohens_dz']:.1f}")
            m.add(f"{tag}Cor", pval(r["corrected_t_p_holm"]))
            m.add(f"{tag}Wil", pval(r["wilcoxon_p_holm"]))
            m.add(f"{tag}Higher", int(r["n_a_higher"]))
            # Practical size: accuracy differences in flows per thousand, macro-F1 differences in
            # multiples of the equivalence margin of 0.005.
            if r["measure"] == "accuracy":
                m.add(f"{tag}PerK", word(round(1000 * abs(r["mean_diff"]))))
            if r["measure"] == "macro_f1":
                m.add(f"{tag}Margins", word(round(abs(r["mean_diff"]) / 0.005)))
        g = read(f"generalisation_bootstrap_{p}.csv")
        if g is not None:
            g = g.set_index("model")
            m.add(f"OG{ptag}Runs", int(g.loc["rf", "n_runs"]))
            for mod in g.index:
                if mod not in TAG:
                    continue
                for k, nm in MEASURES.items():
                    m.add(f"OG{ptag}{TAG[mod]}{nm}", f3(g.loc[mod, k]))
                    m.add(f"OG{ptag}{TAG[mod]}{nm}Lo", f3(g.loc[mod, f"{k}_lo"]))
                    m.add(f"OG{ptag}{TAG[mod]}{nm}Hi", f3(g.loc[mod, f"{k}_hi"]))
                    m.add(f"OG{ptag}{TAG[mod]}{nm}RunStd", f"{g.loc[mod, f'{k}_run_std']:.4f}")
        d = read(f"generalisation_differences_{p}.csv")
        if d is not None:
            for _, r in d.iterrows():
                tag = f"OGD{ptag}{TAG[r['model_a']]}Vs{TAG[r['model_b']]}{MEASURES[r['measure']]}"
                m.add(f"{tag}", f"{r['diff']:+.3f}")
                m.add(f"{tag}Lo", f"{r['lo']:+.3f}")
                m.add(f"{tag}Hi", f"{r['hi']:+.3f}")
        t = read(f"generalisation_time_{p}.csv")
        if t is not None:
            t = t.set_index("model")
            for mod in t.index:
                if mod in TAG and not pd.isna(t.loc[mod, "fit_seconds"]):
                    m.add(f"OT{ptag}{TAG[mod]}Fit", f"{t.loc[mod, 'fit_seconds']:.1f}")
                    m.add(f"OT{ptag}{TAG[mod]}Predict", f"{t.loc[mod, 'predict_seconds']:.2f}")
    gc, gg = read("generalisation_bootstrap_compatible.csv"), read("generalisation_bootstrap_grouped.csv")
    if gc is not None and gg is not None:
        a, b = gc.set_index("model"), gg.set_index("model")
        base = [x for x in ("knn", "knn_cw", "tree", "tree_balanced", "rf", "rf_weighted", "rf_sampled", "boost", "stack",
                            "vote_all") if x in a.index and x in b.index]
        drop = (a.loc[base, "accuracy"] - b.loc[base, "accuracy"])
        m.add("OGAccDropMin", f3(drop.min()))
        m.add("OGAccDropMax", f3(drop.max()))
        m.add("OGAccDropMinPerK", word(round(1000 * drop.min())))
        m.add("OGAccDropMaxPerK", word(round(1000 * drop.max())))
        m.add("OGAccDropAll", "yes" if (drop > 0).all() else "no")
        for mod in base:
            m.add(f"OGDrop{TAG[mod]}MacroF", f3(a.loc[mod, "macro_f1"] - b.loc[mod, "macro_f1"]))
            m.add(f"OGDrop{TAG[mod]}Accuracy", f3(a.loc[mod, "accuracy"] - b.loc[mod, "accuracy"]))
    rk = read("protocol_ranking.csv")
    if rk is not None:
        rk = rk.set_index("measure")
        for k, nm in MEASURES.items():
            m.add(f"OKendall{nm}", f2(rk.loc[k, "kendall_tau_base"]))
            m.add(f"OKendallAll{nm}", f2(rk.loc[k, "kendall_tau_all"]))
    comparison_tables()
    perclass_table(m)


def comparison_tables() -> None:
    sc, sg = read("protocol_summary_compatible.csv"), read("protocol_summary_grouped.csv")
    gc, gg = read("generalisation_bootstrap_compatible.csv"), read("generalisation_bootstrap_grouped.csv")
    if sc is None:
        return
    sc = sc.set_index("model")
    sg = sg.set_index("model") if sg is not None else None
    gc = gc.set_index("model") if gc is not None else None
    gg = gg.set_index("model") if gg is not None else None

    def cell(s, mod, k):
        return f"{f3(s.loc[mod, k + '_mean'])} $\\pm$ {f3(s.loc[mod, k + '_std'])}" if s is not None and mod in s.index else ""

    def gcell(g, mod):
        return (f"{f3(g.loc[mod, 'macro_f1'])} [{f3(g.loc[mod, 'macro_f1_lo'])}, {f3(g.loc[mod, 'macro_f1_hi'])}]"
                if g is not None and mod in g.index else "")
    order = ["knn", "knn_cw", "tree", "tree_balanced", "rf", "rf_weighted", "rf_sampled", "boost"]
    # One table for both protocols: partition scores (mean and standard deviation over the 15
    # partitions) and scores on the generalisation set (macro-F1 with its bootstrap interval).
    # The highest value of each column within a protocol is set in bold.
    lines = ["% Generated by code/ensemble/make_report_numbers.py. Do not edit by hand.",
             "\\begin{table*}[t]", "\\caption{Scores of the models under the compatible and the grouped protocol}",
             "\\label{tab:comparison}", "\\centering", "\\footnotesize", "\\setlength{\\tabcolsep}{4pt}",
             "\\begin{tabular}{lcccccc}", "\\toprule",
             " & \\multicolumn{3}{c}{15 partitions, mean $\\pm$ standard deviation} & "
             "\\multicolumn{3}{c}{Generalisation set} \\\\",
             "\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}",
             "Model & Accuracy & Balanced accuracy & Macro-F1 & Accuracy & Balanced accuracy & Macro-F1 [interval] \\\\"]
    keys = ("accuracy", "balanced_accuracy", "macro_f1")
    for title, s, g in (("Compatible protocol: partitions of $D$ and the set $G$", sc, gc),
                        ("Grouped protocol: grouped partitions of $D_{g}$ and the set $G_{g}$", sg, gg)):
        if s is None:
            continue
        mods = [x for x in order if x in s.index]
        best_s = {k: max(mods, key=lambda x: round(s.loc[x, k + "_mean"], 3)) for k in keys}
        best_g = ({k: max(mods, key=lambda x: round(g.loc[x, k], 3)) for k in keys} if g is not None else {})
        bold = lambda txt, flag: f"\\textbf{{{txt}}}" if flag else txt  # noqa: E731
        lines += ["\\midrule", f"\\multicolumn{{7}}{{@{{}}l}}{{\\textit{{{title}}}}} \\\\", "\\midrule"]
        for mod in mods:
            cells = [bold(cell(s, mod, k), round(s.loc[mod, k + "_mean"], 3) == round(s.loc[best_s[k], k + "_mean"], 3))
                     for k in keys]
            if g is not None and mod in g.index:
                gk = [bold(f3(g.loc[mod, k]), round(g.loc[mod, k], 3) == round(g.loc[best_g[k], k], 3)) for k in keys[:2]]
                mf = bold(f3(g.loc[mod, "macro_f1"]), round(g.loc[mod, "macro_f1"], 3) == round(g.loc[best_g["macro_f1"], "macro_f1"], 3))
                gk.append(f"{mf} [{f3(g.loc[mod, 'macro_f1_lo'])}, {f3(g.loc[mod, 'macro_f1_hi'])}]")
            else:
                gk = ["", "", ""]
            lines.append(f"{LABEL[mod]} & " + " & ".join(cells + gk) + " \\\\")
            if mod == "tree_balanced":
                lines.append("\\cmidrule(l){1-7}")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}"]
    (OUT / "table_comparison.tex").write_text("\n".join(lines) + "\n")
    # dissimilar table: compatible and grouped macro-F1 of the votes and stacking
    order2 = ["rf", "rf_weighted", "vote_forests", "vote_rf_knn", "vote_all", "vote_without_rf", "vote_without_rf_weighted",
              "vote_without_tree", "vote_without_knn_cw", "stack"]
    lines = ["% Generated by code/ensemble/make_report_numbers.py. Do not edit by hand.",
             "\\begin{table}[t]", "\\caption{Dissimilar ensembles}",
             "\\label{tab:dissimilar}", "\\centering", "\\footnotesize", "\\setlength{\\tabcolsep}{3pt}",
             "\\begin{tabular}{lcc}", "\\toprule", "Model & Compatible & Grouped \\\\", "\\midrule"]
    for mod in order2:
        if mod in sc.index:
            lines.append(f"{LABEL[mod]} & {cell(sc, mod, 'macro_f1')} & {cell(sg, mod, 'macro_f1')} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    (OUT / "table_dissimilar.tex").write_text("\n".join(lines) + "\n")


def perclass_table(m: Macros) -> None:
    p = read("protocol_summary_compatible.csv")
    if p is None or not (RESULTS / "predG_compatible").is_dir():
        return
    table = data.load_table()
    from common import protocol as pr, metrics as mt
    _, gen_idx = pr.stratified_holdout(table.y)
    y = table.y[gen_idx]
    cols = ["knn_cw", "tree", "tree_balanced", "rf", "rf_weighted", "rf_sampled", "boost", "vote_all"]
    head = ["Neighb.", "Tree", "Bal. tree", "Plain", "Weighted", "Sampled", "Boost.", "Vote"]
    f1 = {}
    for c in cols:
        files = sorted((RESULTS / "predG_compatible").glob(f"{c}_run*.npy"))
        if files:
            vals = [mt.per_class(mt.confusion_matrix(y, np.load(f).astype(np.int64), 10))["f1"] for f in files]
            f1[c] = np.mean(vals, axis=0)
    lines = ["% Generated by code/ensemble/make_report_numbers.py. Do not edit by hand.",
             "\\begin{table*}[t]", "\\caption{Per-class F1 score on $G$}", "\\label{tab:perclass}", "\\centering",
             "\\footnotesize", "\\setlength{\\tabcolsep}{5pt}", "\\begin{tabular}{l" + "r" * (len(f1) + 1) + "}",
             "\\toprule", "Class & " + " & ".join(h for c, h in zip(cols, head) if c in f1) + " & $o_j$ \\\\", "\\midrule"]
    support = np.bincount(y, minlength=10)
    for c in f1:
        for j in range(10):
            m.add(f"OPc{TAG[c]}F{CLS[j]}", f3(f1[c][j]))
    for j in range(10):
        lines.append(f"{data.CLASS_NAMES[j]} & " + " & ".join(f3(f1[c][j]) for c in cols if c in f1) +
                     f" & {support[j]:,} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}"]
    (OUT / "table_perclass.tex").write_text("\n".join(lines) + "\n")


def conflict_shares(m: Macros) -> None:
    """Share of the rows of each class of D that sit in feature vectors with at least two labels."""
    from common import grouped, protocol as pr
    table = data.load_table()
    dev_idx, _ = pr.stratified_holdout(table.y)
    dev = table.take(dev_idx)
    g = grouped.feature_groups(dev)
    pairs = np.unique(np.stack([g, dev.y], axis=1), axis=0)
    n_labels = np.bincount(pairs[:, 0], minlength=g.max() + 1)
    conf = n_labels[g] > 1
    rows = []
    for j in range(10):
        share = float(conf[dev.y == j].mean())
        m.add(f"OConf{CLS[j]}", f"{100 * share:.0f}")
        rows.append({"class": j, "name": data.CLASS_NAMES[j], "conflicting_share": share})
    pd.DataFrame(rows).to_csv(RESULTS / "conflict_share_by_class.csv", index=False)


def g_conflict(m: Macros) -> None:
    """Confusion of the weighted forest on G inside and outside vectors with conflicting labels."""
    from common import grouped, protocol as pr, metrics as mt
    table = data.load_table()
    _, gen_idx = pr.stratified_holdout(table.y)
    g = grouped.feature_groups(table)
    pairs = np.unique(np.stack([g, table.y], axis=1), axis=0)
    conf = (np.bincount(pairs[:, 0], minlength=g.max() + 1) > 1)[g][gen_idx]
    y = table.y[gen_idx]
    files = sorted((RESULTS / "predG_compatible").glob("rf_weighted_run*.npy"))
    rows = []
    for label, mask in (("Clean", ~conf), ("Conf", conf)):
        cm = sum(mt.confusion_matrix(y[mask], np.load(f).astype(np.int64)[mask], 10) for f in files).astype(float)
        rn = cm / np.maximum(cm.sum(axis=1, keepdims=True), 1)
        for (i, j, nm) in ((3, 4, "DoSExpl"), (4, 3, "ExplDoS"), (2, 3, "BackDoS"), (5, 3, "AnalDoS"), (3, 3, "DoSDoS")):
            m.add(f"OGc{label}{nm}", f"{100 * rn[i, j]:.0f}")
            rows.append({"subset": label, "true": i, "pred": j, "share": rn[i, j]})
        m.add(f"OGc{label}Rows", f"{100 * mask.mean():.1f}")
        m.add(f"OGc{label}Acc", f3(np.trace(cm) / cm.sum()))
    pd.DataFrame(rows).to_csv(RESULTS / "confusion_G_conflict_split.csv", index=False)
    sds = []
    for c in ("rf", "rf_weighted", "rf_sampled"):
        fs = sorted((RESULTS / "predG_compatible").glob(f"{c}_run*.npy"))
        vals = np.array([mt.per_class(mt.confusion_matrix(y, np.load(f).astype(np.int64), 10))["f1"] for f in fs])
        sds.append(vals.std(axis=0, ddof=1).max())
    m.add("OPcMaxRunSd", f3(max(sds)))


