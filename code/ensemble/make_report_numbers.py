def sweeps(m: Macros) -> None:
    e = read("summary_encoding.csv")
    if e is not None:
        e = e.set_index("config")
        for k, tag in (("onehot", "One"), ("ordinal", "Ord")):
            m.add(f"OEnc{tag}F", f3(e.loc[k, "macro_f1_mean"]))
            m.add(f"OEnc{tag}FStd", f3(e.loc[k, "macro_f1_std"]))
            m.add(f"OEnc{tag}Acc", f3(e.loc[k, "accuracy_mean"]))
            m.add(f"OEnc{tag}Bal", f3(e.loc[k, "balanced_accuracy_mean"]))
        m.add("OEncDiff", f3(e.loc["onehot", "macro_f1_mean"] - e.loc["ordinal", "macro_f1_mean"]))
    a = json.loads((RESULTS / "analysis_sweeps.json").read_text())
    # features
    f = read("summary_features.csv").set_index("max_features")
    for phi in f.index:
        w = WORDS[int(phi)]
        m.add(f"OFeat{w}F", f3(f.loc[phi, "macro_f1_mean"]))
        m.add(f"OFeat{w}FStd", f3(f.loc[phi, "macro_f1_std"]))
        m.add(f"OFeat{w}Oob", f3(f.loc[phi, "oob_macro_f1_mean"]))
        m.add(f"OFeat{w}Bal", f3(f.loc[phi, "balanced_accuracy_mean"]))
        m.add(f"OFeat{w}Acc", f3(f.loc[phi, "accuracy_mean"]))
        m.add(f"OFeat{w}S", f3(f.loc[phi, "member_accuracy_mean"]))
        m.add(f"OFeat{w}A", f3(f.loc[phi, "disagreement_mean"]))
        m.add(f"OFeat{w}Q", f3(f.loc[phi, "q_statistic_mean"]))
        m.add(f"OFeat{w}Nodes", f"{int(round(f.loc[phi, 'mean_nodes_mean'])):,}")
    best = f["macro_f1_mean"].idxmax()
    m.add("OFeatBest", int(best))
    # number of encoded features (largest phi of the sweep) and the default square root
    m.add("OFeatEncoded", int(f.index.max()))
    m.add("OFeatSqrt", max(1, int(np.sqrt(int(f.index.max())))))
    fe = {(r["a"]): r for r in a["feature_effects"]}
    for c, r in fe.items():
        w = WORDS[int(c.split("=")[1])]
        m.add(f"OFeatEff{w}", f3(r["mean_diff"]))
        m.add(f"OFeatEffSize{w}", f"{r['paired_effect_size']:.1f}")
    # structure
    st = read("summary_structure.csv")
    cell = lambda d, l, c="macro_f1_mean": st[(st.max_depth == d) & (st.min_samples_leaf == l)][c].iloc[0]  # noqa: E731
    for d in (3, 5, 8, 12, 20, -1):
        m.add(f"ODepth{WORDS[d]}LeafOneF", f3(cell(d, 1)))
    m.add("ODepthNoneLeafTwoF", f3(cell(-1, 2)))
    m.add("ODepthNoneLeafFiftyF", f3(cell(-1, 50)))
    m.add("ODepthTwentyLeafFiftyF", f3(cell(20, 50)))
    m.add("ODepthNoneLeafFiveF", f3(cell(-1, 5)))
    m.add("ODepthNoneLeafTenF", f3(cell(-1, 10)))
    m.add("ODepthNoneLeafTwentyFiveF", f3(cell(-1, 25)))
    for leaf in (1, 25):
        for j in (2, 5, 7):
            m.add(f"OLeaf{WORDS[leaf]}R{CLS[j]}", f3(cell(-1, leaf, f"recall_{j}_mean")))
    m.add("ODepthNoneLeafOneNodes", f"{int(round(cell(-1, 1, 'mean_nodes_mean'))):,}")
    m.add("ODepthNoneLeafFiftyNodes", f"{int(round(cell(-1, 50, 'mean_nodes_mean'))):,}")
    m.add("ODepthNoneLeafOneS", f3(cell(-1, 1, "member_accuracy_mean")))
    m.add("ODepthNoneLeafTwentyFiveS", f3(cell(-1, 25, "member_accuracy_mean")))
    m.add("ODepthTwelveLeafOneS", f3(cell(12, 1, "member_accuracy_mean")))
    m.add("ODepthNoneLeafOneAcc", f3(cell(-1, 1, "accuracy_mean")))
    m.add("ODepthTwentyLeafOneAcc", f3(cell(20, 1, "accuracy_mean")))
    bestcell = st.loc[st["macro_f1_mean"].idxmax()]
    m.add("ODepthBestF", f3(bestcell["macro_f1_mean"]))
    # treatment
    bal = read("summary_balance.csv").set_index("config")
    for k, tag in (("bootstrap0.0,alpha=0.0", "Plain"), ("bootstrap0.0,alpha=0.5", "WeightHalf"),
                   ("bootstrap0.0,alpha=1.0", "WeightFull"), ("bootstrap0.5,alpha=0.0", "BootHalf"), ("bootstrap0.5,alpha=0.5", "BootHalfWeightHalf"),
                   ("bootstrap1.0,alpha=0.0", "BootFull"), ("undermin,alpha=0.0", "UnderMin"),
                   ("under1000,alpha=0.0", "UnderThousand")):
        for c, nm in (("macro_f1", "F"), ("accuracy", "Acc"), ("balanced_accuracy", "Bal"), ("recall_7", "RSeven"),
                      ("recall_2", "RTwo"), ("recall_5", "RFive"), ("recall_8", "REight"), ("f1_7", "FSeven"),
                      ("oob_macro_f1", "Oob")):
            m.add(f"OTr{tag}{nm}", f3(bal.loc[k, f"{c}_mean"]))
        m.add(f"OTr{tag}RSevenStd", f3(bal.loc[k, "recall_7_std"]))
        m.add(f"OTr{tag}FStd", f3(bal.loc[k, "macro_f1_std"]))
    te = {r["a"]: r for r in a["treatment_effects"]}
    for k, tag in (("bootstrap0.5,alpha=0.0", "BootHalf"), ("bootstrap0.5,alpha=0.5", "BootHalfWeightHalf"), ("bootstrap0.0,alpha=0.5", "WeightHalf")):
        m.add(f"OTrEff{tag}", f3(te[k]["mean_diff"]))
        m.add(f"OTrEffSize{tag}", f"{te[k]['paired_effect_size']:.1f}")


