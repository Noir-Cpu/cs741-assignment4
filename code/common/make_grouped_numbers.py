"""Write LaTeX macros and tables for report/common/grouped_protocol.tex from results/common/grouped_*.

Run after run_grouped_baselines.py:

    .venv/bin/python code/common/make_grouped_numbers.py

Outputs (in report/common/): numbers_grouped.tex (macros with the prefix Gp, defined with
\\providecommand so that a double input is harmless), table_grouped_ranking.tex and
table_grouped_balance.tex. The old make_report_numbers.py is not touched.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from common import data  # noqa: E402

OUT = data.REPO_ROOT / "report" / "common"
RES = data.RESULTS_COMMON
MODELS = {"knn": "Knn", "knn_cw": "KnnCw", "tree": "Tree", "tree_balanced": "TreeBalanced"}
MODEL_LABEL = {"knn": "neighbours", "knn_cw": "neighbours, weighted", "tree": "tree",
               "tree_balanced": "tree, balanced"}
MEASURES = {"accuracy": "Accuracy", "macro_f1": "MacroF", "weighted_f1": "WeightedF",
            "balanced_accuracy": "BalAcc"}
TABLE_MEASURES = ("macro_f1", "balanced_accuracy", "accuracy")
MEASURE_LABEL = {"accuracy": "Accuracy", "macro_f1": "Macro-F1", "balanced_accuracy": "Balanced accuracy"}
WORDS = {0: "zero", 1: "one", 2: "two", 3: "three", 4: "four", 5: "five", 6: "six", 7: "seven",
         8: "eight", 9: "nine"}


def thousands(x) -> str:
    return f"{int(round(x)):,}"


def pct(x, digits=1) -> str:
    return f"{100 * x:.{digits}f}"


def count(x) -> str:
    x = int(round(x))
    return WORDS.get(x, f"{x:,}") if x < 10 else f"{x:,}"


def pvalue(p) -> str:
    return "$p < 0.001$" if p < 0.001 else f"$p = {p:.3f}$"


class Macros:
    def __init__(self):
        self.lines = ["% Generated by code/common/make_grouped_numbers.py. Do not edit by hand."]

    def add(self, name, value):
        self.lines.append(f"\\providecommand{{\\{name}}}{{{value}}}")

    def write(self, path: Path):
        path.write_text("\n".join(self.lines) + "\n")


def param_text(model: str, p: dict) -> dict:
    if model.startswith("knn"):
        return {"K": count(p["k"]), "Metric": p["metric"].capitalize(), "Power": f"{p['class_weight_power']:g}"}
    return {"Depth": "unrestricted" if p["max_depth"] is None else count(p["max_depth"]),
            "Leaf": count(p["min_samples_leaf"])}


def main() -> None:
    m = Macros()
    split = json.loads((RES / "grouped_split.json").read_text())
    m.add("GpNDev", thousands(split["n_development_grouped"]))
    m.add("GpNGen", thousands(split["n_generalisation_grouped"]))
    m.add("GpNGroupsFile", thousands(split["groups_full_table"]["n_groups"]))
    m.add("GpNGroupsDev", thousands(split["groups_development_grouped"]["n_groups"]))
    m.add("GpPDupDev", pct(split["groups_development_standard"]["n_excess_rows"] / split["n_development_standard"]))
    m.add("GpPRepeatedRows", pct(split["groups_development_standard"]["share_rows_in_repeated_groups"]))
    m.add("GpNConflictGroups", thousands(split["groups_development_standard"]["n_conflicting_groups"]))
    m.add("GpPConflictRows", pct(split["groups_development_standard"]["share_rows_in_conflicting_groups"]))
    m.add("GpLargestGroup", thousands(split["groups_development_grouped"]["largest_group"]))
    tw = split["mean_twin_share"]
    m.add("GpTwinStdComparison", pct(tw["standard_comparison"]))
    m.add("GpTwinStdTuning", pct(tw["standard_tuning"]))
    m.add("GpTwinGroupedComparison", pct(tw["grouped_comparison"]))
    m.add("GpTwinStdSameLabel", pct(split["mean_twin_share_same_label"]["standard_comparison"]))
    m.add("GpTwinGStd", pct(split["twin_share_G_standard"]))
    m.add("GpTwinGGrouped", pct(split["twin_share_G_grouped"]))
    m.add("GpGroupsCrossing", split["max_groups_crossing_grouped"])
    w7 = split["class7"]
    m.add("GpSevenTotal", w7["class7_total"])
    m.add("GpSevenGroups", w7["class7_groups_total"])
    m.add("GpSevenDev", w7["class7_D_g"])
    m.add("GpSevenGen", w7["class7_G_g"])
    m.add("GpSevenFoldMin", w7["class7_test_count_per_fold_min"])
    m.add("GpSevenFoldMax", w7["class7_test_count_per_fold_max"])
    m.add("GpGenMaxDiff", split["max_abs_class_count_difference_G_g_vs_shared_G"])
    bal = split["comparison_balance"]
    dev = np.array(bal["max_relative_deviation_per_class"])
    m.add("GpBalMaxDevOthers", pct(np.delete(dev, 7).max(), 2))
    m.add("GpBalMaxDevSeven", pct(dev[7], 1))
    m.add("GpFoldMin", thousands(bal["fold_size_min"]))
    m.add("GpFoldMax", thousands(bal["fold_size_max"]))
    m.add("GpSmallClasses", count(len(split["classes_with_fewer_than_20_test_rows"])))
    ideal = bal["ideal_per_class"]
    m.add("GpIdealSeven", f"{ideal[7]:.1f}")
    twins = pd.read_csv(RES / "grouped_twin_share.csv")
    sub = twins[twins["protocol"] == "standard_comparison"]["twin_share"]
    m.add("GpTwinStdMin", pct(sub.min()))
    m.add("GpTwinStdMax", pct(sub.max()))

    # class counts table
    counts = pd.read_csv(RES / "grouped_class_counts.csv")
    rows = ["% Generated by code/common/make_grouped_numbers.py. Do not edit by hand.",
            "\\begin{table}[t]", "\\caption{Class sizes of the grouped development and generalisation sets}",
            "\\label{tab:sh-grouped-balance}", "\\centering", "\\footnotesize",
            "\\begin{tabular}{rlrrrr}", "\\toprule", "Class & Name & $D$ & $D_{\\mathrm{g}}$ & $G$ & $G_{\\mathrm{g}}$ \\\\",
            "\\midrule"]
    for _, r in counts.iterrows():
        rows.append(f"{int(r['class'])} & {r['name']} & {thousands(r['shared_D'])} & {thousands(r['D_g'])} & "
                    f"{thousands(r['shared_G'])} & {thousands(r['G_g'])} \\\\")
    rows += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    (OUT / "table_grouped_balance.tex").write_text("\n".join(rows) + "\n")

    # retuning
    retune = json.loads((RES / "grouped_retuning.json").read_text())
    n_changed = 0
    for model, token in MODELS.items():
        if model not in retune:
            continue
        r = retune[model]
        n_changed += int(r["configuration_changed"])
        for key, val in param_text(model, r["standard_protocol_best"]).items():
            m.add(f"GpStd{token}{key}", val)
        for key, val in param_text(model, r["grouped_best"]).items():
            m.add(f"GpTune{token}{key}", val)
        m.add(f"GpTune{token}Score", f"{r['grouped_cv_macro_f1_of_grouped_best']:.3f}")
        m.add(f"GpTune{token}ScoreOfStd", f"{r['grouped_cv_macro_f1_of_standard_best']:.3f}")
        m.add(f"GpTune{token}StdScore", f"{r['standard_cv_macro_f1_of_standard_best']:.3f}")
        m.add(f"GpTune{token}Gain", f"{r['grouped_cv_macro_f1_of_grouped_best'] - r['grouped_cv_macro_f1_of_standard_best']:.3f}")
    m.add("GpNChanged", count(n_changed))

    # scores
    summary = pd.read_csv(RES / "grouped_comparison_summary.csv").set_index("model")
    std = pd.read_csv(RES / "comparison_summary.csv").set_index("model")
    for model, token in MODELS.items():
        for measure, mt in MEASURES.items():
            m.add(f"Gp{token}{mt}Mean", f"{summary.loc[model, measure + '_mean']:.3f}")
            m.add(f"Gp{token}{mt}Std", f"{summary.loc[model, measure + '_std']:.3f}")
            m.add(f"Gp{token}{mt}G", f"{summary.loc[model, measure + '_G']:.3f}")
            m.add(f"Gp{token}{mt}Drop", f"{std.loc[model, measure + '_mean'] - summary.loc[model, measure + '_mean']:.3f}")
            m.add(f"Gp{token}{mt}DropG", f"{std.loc[model, measure + '_G'] - summary.loc[model, measure + '_G']:.3f}")
        retuned = f"{model}_retuned"
        if retuned in summary.index:
            for measure, mt in MEASURES.items():
                m.add(f"Gp{token}Retuned{mt}Mean", f"{summary.loc[retuned, measure + '_mean']:.3f}")
                m.add(f"Gp{token}Retuned{mt}G", f"{summary.loc[retuned, measure + '_G']:.3f}")
    rv = pd.read_csv(RES / "grouped_retuned_vs_reused.csv")
    for _, r in rv.iterrows():
        m.add(f"Gp{MODELS[r['model']]}Retuned{MEASURES[r['measure']]}Diff", f"{r['mean_diff']:.3f}")
        m.add(f"Gp{MODELS[r['model']]}Retuned{MEASURES[r['measure']]}Wil", pvalue(r["wilcoxon_p"]))

    # statistics
    stat = pd.read_csv(RES / "grouped_comparison_stats.csv")
    for _, r in stat.iterrows():
        a, b, mt = MODELS[r["model_a"]], MODELS[r["model_b"]], MEASURES[r["measure"]]
        m.add(f"GpSt{a}{b}{mt}Diff", f"{r['mean_diff']:.3f}")
        m.add(f"GpSt{a}{b}{mt}AbsDiff", f"{abs(r['mean_diff']):.3f}")
        m.add(f"GpSt{a}{b}{mt}Dz", f"{r['cohens_dz']:.1f}")
        m.add(f"GpSt{a}{b}{mt}Wil", pvalue(r["wilcoxon_p"]))
        m.add(f"GpSt{a}{b}{mt}Cor", pvalue(r["corrected_t_p"]))
    prim = pd.read_csv(RES / "comparison_stats.csv")
    for _, r in prim.iterrows():
        a, b, mt = MODELS[r["model_a"]], MODELS[r["model_b"]], MEASURES[r["measure"]]
        m.add(f"GpPrim{a}{b}{mt}Diff", f"{r['mean_diff']:.3f}")
    fr = pd.read_csv(RES / "grouped_comparison_friedman.csv").set_index("measure")
    for measure, mt in MEASURES.items():
        m.add(f"GpFriedman{mt}P", pvalue(fr.loc[measure, "friedman_p"]))
        m.add(f"GpCD{mt}", f"{fr.loc[measure, 'nemenyi_critical_difference']:.2f}")
        for model, token in MODELS.items():
            m.add(f"GpRank{token}{mt}", f"{fr.loc[measure, 'rank_' + model]:.2f}")
    post = pd.read_csv(RES / "grouped_comparison_posthoc.csv")
    for _, r in post.iterrows():
        a, b, mt = MODELS[r["model_a"]], MODELS[r["model_b"]], MEASURES[r["measure"]]
        m.add(f"GpHolm{a}{b}{mt}", pvalue(r["holm_wilcoxon_p"]))
        m.add(f"GpNem{a}{b}{mt}", pvalue(r["nemenyi_p"]))

    # per-class F1 on G_g and recall of the rare classes
    per_class = pd.read_csv(RES / "grouped_generalisation_per_class.csv")
    tokens = ["Normal", "Recon", "Backdoor", "DoS", "Exploits", "Analysis", "Fuzzers", "Worms", "Shellcode", "Generic"]
    for model, token in MODELS.items():
        sub = per_class[per_class["model"] == model]
        for c, ct in enumerate(tokens):
            m.add(f"Gp{token}F{ct}", f"{sub[sub['class'] == c].iloc[0]['f1']:.3f}")
            m.add(f"Gp{token}R{ct}", f"{sub[sub['class'] == c].iloc[0]['recall']:.3f}")
    std_pc = pd.read_csv(RES / "generalisation_per_class.csv")
    for model, token in MODELS.items():
        sub = std_pc[std_pc["model"] == model]
        for c, ct in enumerate(tokens):
            m.add(f"GpPrim{token}F{ct}", f"{sub[sub['class'] == c].iloc[0]['f1']:.3f}")
    # per-class F1 in the cross-validation, grouped and primary
    cv_pc = pd.read_csv(RES / "grouped_comparison_per_class.csv")
    std_cv = pd.read_csv(RES / "comparison_per_class.csv")
    for model, token in MODELS.items():
        g = cv_pc[cv_pc["model"] == model].groupby("class")["f1"].mean()
        p = std_cv[std_cv["model"] == model].groupby("class")["f1"].mean()
        drop = (p - g)
        m.add(f"Gp{token}LargestClassDrop", f"{drop.max():.3f}")
        m.add(f"Gp{token}LargestClassDropName", data.CLASS_NAMES[int(drop.idxmax())])
        m.add(f"Gp{token}SevenCVF", f"{g[7]:.3f}")
        m.add(f"Gp{token}PrimSevenCVF", f"{p[7]:.3f}")

    # conclusion flags and rank agreement
    concl = json.loads((RES / "grouped_conclusion.json").read_text())
    for measure, mt in MEASURES.items():
        r = concl["per_measure"][measure]
        m.add(f"GpTau{mt}", f"{r['kendall_tau']:.2f}")
        m.add(f"GpSame{mt}", "unchanged" if r["ranking_unchanged"] else "changed")
        m.add(f"GpSameG{mt}", "unchanged" if r["ranking_unchanged_on_G"] else "changed")
    m.add("GpAssignmentTwoSame", "unchanged" if concl["assignment2_conclusion_unchanged"] else "changed")
    gc = concl["assignment2_conclusion_grouped"]
    m.add("GpTreeMacroHigher", "higher" if gc["tree_macro_f1_higher"] else "not higher")
    m.add("GpTreeBalAccHigher", "higher" if gc["tree_balanced_accuracy_higher"] else "not higher")
    m.add("GpKnnAccHigher", "higher" if gc["knn_accuracy_higher"] else "not higher")
    rt = json.loads((RES / "grouped_runtimes.json").read_text())
    for stage in ("split", "tune", "compare"):
        if stage in rt:
            m.add(f"GpRt{stage.capitalize()}", f"{rt[stage]['wall_seconds'] / 60:.1f}")
    m.add("GpThreads", rt.get("threads", ""))
    m.add("GpPeakRss", f"{rt.get('peak_rss_mb', 0) / 1024:.1f}")

    # side-by-side ranking table
    side = pd.read_csv(RES / "grouped_ranking_comparison.csv")
    rows = ["% Generated by code/common/make_grouped_numbers.py. Do not edit by hand.",
            "\\begin{table*}[t]",
            "\\caption{Scores and ranks of the baselines under the primary and the grouped protocol}",
            "\\label{tab:sh-grouped-ranking}", "\\centering", "\\footnotesize",
            "\\begin{tabular}{lcccccccccccc}", "\\toprule",
            " & " + " & ".join(f"\\multicolumn{{4}}{{c}}{{{MEASURE_LABEL[k]}}}" for k in TABLE_MEASURES) + " \\\\",
            "\\cmidrule(lr){2-5}\\cmidrule(lr){6-9}\\cmidrule(lr){10-13}",
            "Model & " + " & ".join(["Primary & Rank & Grouped & Rank"] * 3) + " \\\\", "\\midrule"]
    for model in MODELS:
        cells = []
        for measure in TABLE_MEASURES:
            r = side[(side["measure"] == measure) & (side["model"] == model)].iloc[0]
            cells += [f"{r['primary_mean']:.3f}", f"{int(r['primary_rank'])}", f"{r['grouped_mean']:.3f}",
                      f"{int(r['grouped_rank'])}"]
        rows.append(f"{MODEL_LABEL[model]} & " + " & ".join(cells) + " \\\\")
    rows += ["\\bottomrule", "\\end{tabular}", "\\end{table*}"]
    (OUT / "table_grouped_ranking.tex").write_text("\n".join(rows) + "\n")
    m.write(OUT / "numbers_grouped.tex")
    print(f"wrote {OUT / 'numbers_grouped.tex'} with {len(m.lines) - 1} macros")


if __name__ == "__main__":
    main()
