"""Write LaTeX macros and tables for the report from results/common.

Every number in report/common/*.tex comes from this script, so the text cannot
drift from the result files. Run after run_data_quality.py, run_baselines.py and
run_preprocessing_ablation.py:

    .venv/bin/python code/common/make_report_numbers.py

Outputs (in report/common/): numbers.tex, table_classes.tex, table_baselines.tex,
table_baseline_perclass.tex and table_ablation.tex.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from common import data, protocol  # noqa: E402

OUT = data.REPO_ROOT / "report" / "common"
RES = data.RESULTS_COMMON
MODELS = {"knn": "Knn", "knn_cw": "KnnCw", "tree": "Tree", "tree_balanced": "TreeBalanced"}
MODEL_LABEL = {"knn": "k-nearest neighbours", "knn_cw": "k-nearest neighbours, class weights",
               "tree": "classification tree", "tree_balanced": "classification tree, balanced weights"}
MEASURES = {"accuracy": "Accuracy", "macro_f1": "MacroF", "weighted_f1": "WeightedF",
            "balanced_accuracy": "BalAcc"}
MEASURE_LABEL = {"accuracy": "Accuracy", "macro_f1": "Macro-F1", "weighted_f1": "Weighted-F1",
                 "balanced_accuracy": "Balanced accuracy"}
PERCLASS_HEADER = {"knn": "Neighbours", "knn_cw": "Neighbours, weighted", "tree": "Tree",
                   "tree_balanced": "Tree, balanced"}
WORDS = {1: "one", 2: "two", 3: "three", 4: "four", 5: "five", 6: "six", 7: "seven", 8: "eight", 9: "nine"}


def thousands(x) -> str:
    return f"{int(round(x)):,}"


def count(x) -> str:
    x = int(round(x))
    return WORDS.get(x, str(x)) if x < 10 else f"{x:,}"


def pct(x, digits=1) -> str:
    return f"{100 * x:.{digits}f}"


def sig(x, digits=2) -> str:
    return f"{x:.{digits}g}" if x >= 0.01 else f"{x:.2g}"


class Macros:
    def __init__(self):
        self.lines = ["% Generated by code/common/make_report_numbers.py. Do not edit by hand."]

    def add(self, name: str, value) -> None:
        self.lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    def write(self, path: Path) -> None:
        path.write_text("\n".join(self.lines) + "\n")


def data_macros(m: Macros) -> None:
    q = json.loads((RES / "data_quality" / "summary.json").read_text())
    split = json.loads((RES / "split.json").read_text())
    classes = pd.read_csv(RES / "data_quality" / "class_distribution.csv")
    m.add("nFile", thousands(q["n_rows_file"]))
    m.add("nDev", thousands(split["n_development"]))
    m.add("nGen", thousands(split["n_generalisation"]))
    m.add("nNumeric", q["n_numeric_features"])
    m.add("nNominal", count(q["n_nominal_features"]))
    m.add("nServiceMissing", thousands(q["service_missing_count_file"]))
    m.add("pServiceMissing", pct(q["service_missing_share_file"]))
    m.add("pServiceByProtoMin", pct(q["service_missing_share_by_proto_min"]))
    m.add("pServiceByStateMin", pct(q["service_missing_share_by_state_min"]))
    m.add("nProto", q["nominal_cardinality_development"]["proto"])
    m.add("nServiceCard", q["nominal_cardinality_development"]["service"])
    m.add("nStateCard", q["nominal_cardinality_development"]["state"])
    m.add("nProtoRare", q["proto_n_rare_categories"])
    m.add("nProtoRareRows", thousands(q["proto_rows_in_rare_categories"]))
    m.add("pProtoRareRows", pct(q["proto_rows_in_rare_categories"] / q["n_rows_development"]))
    m.add("nProtoGrouped", q["proto_categories_after_grouping"])
    m.add("pProtoTop", pct(q["proto_top3_share"]))
    m.add("protoThreshold", q["proto_rare_threshold"])
    m.add("nFtpOut", q["is_ftp_login_out_of_range_rows"])
    m.add("pFtpAgree", pct(q["is_ftp_login_equals_ct_ftp_cmd_share"], 3))
    m.add("nDup", thousands(q["duplicate_feature_vectors_excess_rows"]))
    m.add("pDup", pct(q["duplicate_feature_vectors_excess_rows"] / q["n_rows_development"]))
    m.add("nConflictVec", thousands(q["feature_vectors_with_conflicting_labels"]))
    m.add("nConflictRows", thousands(q["rows_in_conflicting_feature_vectors"]))
    m.add("pConflictRows", pct(q["rows_in_conflicting_feature_vectors"] / q["n_rows_development"]))
    m.add("pCeiling", pct(q["resubstitution_accuracy_ceiling"]))
    m.add("pFoldDup", pct(q["tuning_fold0_test_rows_with_training_duplicate_share"]))
    m.add("nCorr", q["n_pairs_correlation_at_least_0.9"])
    m.add("nLogged", q["log_transformed_features"])
    m.add("skewMin", f"{q['skewness_before_log_min']:.2f}")
    m.add("skewMax", f"{q['skewness_before_log_max']:.1f}")
    m.add("skewAfter", f"{q['skewness_after_log_max']:.2f}")
    m.add("scaleMin", f"{q['median_abs_smallest_positive'][1]:.2g}".replace("0.0043", "0.0043"))
    m.add("scaleMax", thousands(q["median_abs_largest"][1]))
    m.add("nOutlierFeatures", q["n_features_with_outliers_above_10_percent"])
    m.add("pOutlierMax", pct(q["outlier_share_iqr_range"][1]))
    total = classes["count_file"].sum()
    m.add("nClassMax", thousands(classes["count_file"].max()))
    m.add("nClassMin", thousands(classes["count_file"].min()))
    m.add("ratioImbalance", thousands(classes["count_file"].max() / classes["count_file"].min()))
    share = classes["count_file"].max() / total
    m.add("pMajorityAccuracy", pct(share))
    f_major = 2 * share * 1.0 / (share + 1.0)
    m.add("majorityMacroF", f"{f_major / len(classes):.3f}")
    worms_dev = int(classes.loc[classes["name"] == "Worms", "count_development"].iloc[0])
    m.add("nWormsDev", worms_dev)
    m.add("nWormsFold", int(round(worms_dev / protocol.N_FOLDS)))
    m.add("masterSeed", protocol.MASTER_SEED)

    gen_counts = split["class_counts_generalisation"]
    rows = ["% Generated by code/common/make_report_numbers.py. Do not edit by hand.",
            "\\begin{table}[t]", "\\caption{Class sizes of the data set}", "\\label{tab:sh-classes}",
            "\\centering", "\\begin{tabular}{rlrrr}", "\\toprule",
            "Class & Name & File & $D$ & $G$ \\\\", "\\midrule"]
    for _, r in classes.iterrows():
        c = int(r["class"])
        rows.append(f"{c} & {r['name']} & {thousands(r['count_file'])} & "
                    f"{thousands(r['count_development'])} & {thousands(gen_counts[c])} \\\\")
    rows += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    (OUT / "table_classes.tex").write_text("\n".join(rows) + "\n")


def hardware_macros(m: Macros) -> None:
    hw = json.loads((RES / "hardware.json").read_text())
    cpu = hw["cpu_model"].split(" w/ ")[0]
    m.add("cpuModel", cpu)
    m.add("logicalCores", hw["logical_cores"])
    mem_kb = [int(line.split()[1]) for line in Path("/proc/meminfo").read_text().splitlines()
              if line.startswith("MemTotal")][0]
    m.add("ramGB", f"{mem_kb / 1024 / 1024:.0f}")
    m.add("numbaThreads", hw["numba_threads"])
    m.add("numbaVersion", hw["numba"])
    m.add("numpyVersion", hw["numpy"])
    m.add("scipyVersion", hw["scipy"])
    m.add("maxBins", "65,535")


def baseline_macros(m: Macros) -> None:
    summary = pd.read_csv(RES / "comparison_summary.csv").set_index("model")
    for model, token in MODELS.items():
        if model not in summary.index:
            continue
        for measure, mt in MEASURES.items():
            m.add(f"Bl{token}{mt}Mean", f"{summary.loc[model, measure + '_mean']:.3f}")
            m.add(f"Bl{token}{mt}Std", f"{summary.loc[model, measure + '_std']:.3f}")
            m.add(f"Bl{token}{mt}G", f"{summary.loc[model, measure + '_G']:.3f}")
        for column, ct in (("prep_seconds", "Prep"), ("fit_seconds", "Fit"), ("predict_seconds", "Predict")):
            m.add(f"Bl{token}{ct}Mean", f"{summary.loc[model, column + '_mean']:.1f}")
            m.add(f"Bl{token}{ct}G", f"{summary.loc[model, column + '_G']:.1f}")
    knn = json.loads((RES / "knn_best_params.json").read_text())
    tree = json.loads((RES / "tree_best_params.json").read_text())
    for model, token in (("knn", "Knn"), ("knn_cw", "KnnCw")):
        p = knn[model]
        m.add(f"Bl{token}K", count(p["k"]))
        m.add(f"Bl{token}Metric", p["metric"].capitalize())
        m.add(f"Bl{token}Weights", p["weights"])
        m.add(f"Bl{token}Power", f"{p['class_weight_power']:g}")
        m.add(f"Bl{token}Tune", f"{p['cv_macro_f1_mean']:.3f}")
    for model, token, p in (("tree", "Tree", tree), ("tree_balanced", "TreeBalanced", tree.get("balanced_variant"))):
        if p is None:
            continue
        m.add(f"Bl{token}Criterion", p["criterion"])
        m.add(f"Bl{token}Depth", "unrestricted" if p["max_depth"] is None else count(p["max_depth"]))
        m.add(f"Bl{token}Leaf", count(p["min_samples_leaf"]))
        m.add(f"Bl{token}Class", "balanced" if p["class_weight"] == "balanced" else "none")
        m.add(f"Bl{token}Tune", f"{p['cv_macro_f1_mean']:.3f}")
    # per-class scores on G and two large confusions
    class_tokens = ["Normal", "Recon", "Backdoor", "DoS", "Exploits", "Analysis", "Fuzzers", "Worms",
                    "Shellcode", "Generic"]
    per_class_g = pd.read_csv(RES / "generalisation_per_class.csv")
    for model, token in MODELS.items():
        sub = per_class_g[per_class_g["model"] == model]
        if sub.empty:
            continue
        for c, ct in enumerate(class_tokens):
            row = sub[sub["class"] == c].iloc[0]
            m.add(f"Bl{token}F{ct}", f"{row['f1']:.3f}")
            m.add(f"Bl{token}R{ct}", f"{row['recall']:.3f}")
            m.add(f"Bl{token}P{ct}", f"{row['precision']:.3f}")
        cm = np.loadtxt(RES / f"confusion_G_{model}.csv", delimiter=",", dtype=int)
        m.add(f"Bl{token}DoSAsExploits", thousands(cm[3, 4]))
        m.add(f"Bl{token}ExploitsAsDoS", thousands(cm[4, 3]))
        m.add(f"Bl{token}NormalAsFuzzers", thousands(cm[0, 6]))
        m.add(f"Bl{token}FuzzersAsNormal", thousands(cm[6, 0]))
        m.add(f"Bl{token}WormsHit", count(cm[7, 7]))
        m.add(f"Bl{token}WormsSupport", int(cm[7].sum()))
    stats_frame = pd.read_csv(RES / "comparison_stats.csv")

    def pvalue(p):
        return "$p < 0.001$" if p < 0.001 else f"$p = {p:.3f}$"

    for _, r in stats_frame.iterrows():
        a, b = MODELS[r["model_a"]], MODELS[r["model_b"]]
        mt = MEASURES[r["measure"]]
        m.add(f"St{a}{b}{mt}Diff", f"{r['mean_diff']:.3f}")
        m.add(f"St{a}{b}{mt}AbsDiff", f"{abs(r['mean_diff']):.3f}")
        m.add(f"St{a}{b}{mt}Dz", f"{r['cohens_dz']:.1f}")
        m.add(f"St{a}{b}{mt}Wil", pvalue(r["wilcoxon_p"]))
        m.add(f"St{a}{b}{mt}Cor", pvalue(r["corrected_t_p"]))
    weak = per_class_g[per_class_g["class"].isin([2, 5])]["f1"].max()
    m.add("weakFMax", f"{weak:.3f}")
    gaps = []
    for model in MODELS:
        if model in summary.index:
            for measure in MEASURES:
                gaps.append(abs(summary.loc[model, measure + "_G"] - summary.loc[model, measure + "_mean"]))
    m.add("gMaxDiff", f"{max(gaps):.3f}")
    first = summary.index[0]
    m.add("nTestFold", thousands(round(json.loads((RES / "split.json").read_text())["n_development"] / protocol.N_FOLDS)))
    friedman = pd.read_csv(RES / "comparison_friedman.csv").set_index("measure")
    m.add("FriedmanCD", f"{friedman['nemenyi_critical_difference'].iloc[0]:.2f}")
    runtimes = json.loads((RES / "runtimes.json").read_text())
    for stage in ("tune_knn", "tune_tree", "compare", "final"):
        if stage in runtimes:
            m.add(f"rt{''.join(w.capitalize() for w in stage.split('_'))}", f"{runtimes[stage]['wall_seconds'] / 60:.1f}")
    structure = json.loads((RES / "tree_structure.json").read_text())
    m.add("BlTreeNodes", thousands(structure["n_nodes"]))
    m.add("BlTreeLeaves", thousands(structure["n_leaves"]))
    m.add("BlTreeDepthG", structure["depth"])

    # tables
    rows = ["% Generated by code/common/make_report_numbers.py. Do not edit by hand.",
            "\\begin{table*}[t]", "\\caption{Baseline scores: mean and standard deviation over 15 partitions, and score on $G$}",
            "\\label{tab:sh-baselines}", "\\centering", "\\footnotesize",
            "\\begin{tabular}{lcccccccc}", "\\toprule",
            " & \\multicolumn{2}{c}{Accuracy} & \\multicolumn{2}{c}{Macro-F1} & \\multicolumn{2}{c}{Weighted-F1}"
            " & \\multicolumn{2}{c}{Balanced accuracy} \\\\",
            "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}\\cmidrule(lr){8-9}",
            "Model & 15 partitions & $G$ & 15 partitions & $G$ & 15 partitions & $G$ & 15 partitions & $G$ \\\\",
            "\\midrule"]
    for model in MODELS:
        if model not in summary.index:
            continue
        cells = []
        for measure in MEASURES:
            cells.append(f"{summary.loc[model, measure + '_mean']:.3f} $\\pm$ {summary.loc[model, measure + '_std']:.3f}")
            cells.append(f"{summary.loc[model, measure + '_G']:.3f}")
        rows.append(f"{MODEL_LABEL[model]} & " + " & ".join(cells) + " \\\\")
    rows += ["\\bottomrule", "\\end{tabular}", "\\end{table*}"]
    (OUT / "table_baselines.tex").write_text("\n".join(rows) + "\n")

    per_class = pd.read_csv(RES / "generalisation_per_class.csv")
    models = [mm for mm in MODELS if mm in set(per_class["model"])]
    groups = [("Neighbours", ["knn", "knn_cw"], ["plain", "weighted"]), ("Tree", ["tree", "tree_balanced"], ["plain", "balanced"])]
    models = [mm for mm in MODELS if mm in set(per_class["model"])]
    head1 = " & ".join(f"\\multicolumn{{2}}{{c}}{{{name}}}" for name, _, _ in groups)
    head2 = " & ".join(" & ".join(sub) for _, _, sub in groups)
    rows = ["% Generated by code/common/make_report_numbers.py. Do not edit by hand.",
            "\\begin{table}[t]", "\\caption{Per-class F1 score of the baselines on $G$}",
            "\\label{tab:sh-baseline-perclass}", "\\centering", "\\footnotesize", "\\setlength{\\tabcolsep}{3pt}",
            "\\begin{tabular}{rlrrrrr}", "\\toprule",
            f" & & {head1} & \\\\", "\\cmidrule(lr){3-4}\\cmidrule(lr){5-6}",
            f"Class & Name & {head2} & Support \\\\", "\\midrule"]
    for c in range(data.N_CLASSES):
        vals = [per_class[(per_class["model"] == mm) & (per_class["class"] == c)].iloc[0] for mm in models]
        rows.append(f"{c} & {data.CLASS_NAMES[c]} & " + " & ".join(f"{v['f1']:.3f}" for v in vals)
                    + f" & {thousands(vals[0]['support'])} \\\\")
    rows += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    (OUT / "table_baseline_perclass.tex").write_text("\n".join(rows) + "\n")


def ablation_macros(m: Macros) -> None:
    path = RES / "preprocessing_ablation.csv"
    if not path.exists():
        return
    frame = pd.read_csv(path)
    rows = ["% Generated by code/common/make_report_numbers.py. Do not edit by hand.",
            "\\begin{table*}[t]", "\\caption{Ablation results on the tuning folds}",
            "\\label{tab:sh-ablation}", "\\centering", "\\footnotesize",
            "\\begin{tabular}{llrcc}", "\\toprule",
            "Model & Variant & Columns & Macro-F1 & Accuracy \\\\", "\\midrule"]
    for model, label in (("knn", "k-nearest neighbours"), ("tree", "classification tree")):
        sub = frame[frame["model"] == model]
        for i, (_, r) in enumerate(sub.iterrows()):
            rows.append(f"{label if i == 0 else ''} & {r['variant']} & {int(r['n_features'])} & "
                        f"{r['macro_f1_mean']:.3f} $\\pm$ {r['macro_f1_std']:.3f} & "
                        f"{r['accuracy_mean']:.3f} $\\pm$ {r['accuracy_std']:.3f} \\\\")
        rows.append("\\midrule")
    rows[-1] = "\\bottomrule"
    rows += ["\\end{tabular}", "\\end{table*}"]
    (OUT / "table_ablation.tex").write_text("\n".join(rows) + "\n")
    tokens = {"full pipeline": "Full", "no logarithm": "NoLog", "no standardisation": "NoStd",
              "no logarithm and no standardisation": "NoLogStd", "redundant columns kept": "Redundant",
              "no rare-category grouping": "NoRare", "raw numeric columns": "Raw",
              "logarithm and standardisation": "LogStd", "redundant columns dropped": "Dropped",
              "255 bins per feature": "BinsLow", "4095 bins per feature": "BinsMid"}
    cols = frame.set_index(["model", "variant"])["n_features"]
    m.add("AbKnnFullColumns", int(cols[("knn", "full pipeline")]))
    m.add("AbKnnNoRareColumns", int(cols[("knn", "no rare-category grouping")]))
    for model, token in (("knn", "Knn"), ("tree", "Tree")):
        for _, r in frame[frame["model"] == model].iterrows():
            for measure, mt in (("macro_f1", "MacroF"), ("accuracy", "Accuracy")):
                m.add(f"Ab{token}{tokens[r['variant']]}{mt}", f"{r[measure + '_mean']:.3f}")


def main() -> None:
    m = Macros()
    data_macros(m)
    if (RES / "hardware.json").exists():
        hardware_macros(m)
    if (RES / "comparison_summary.csv").exists():
        baseline_macros(m)
    ablation_macros(m)
    m.write(OUT / "numbers.tex")
    print(f"wrote {OUT / 'numbers.tex'} with {len(m.lines) - 1} macros")


if __name__ == "__main__":
    main()
